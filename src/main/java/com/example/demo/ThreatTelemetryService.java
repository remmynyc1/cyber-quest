package com.example.demo;

import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.stereotype.Service;

import java.util.List;
import java.util.Random;

@Service
public class ThreatTelemetryService {

    private final SecurityLogRepository logRepository;
    private final Random random = new Random();

    private final List<String> eventTypes = List.of(
        "BRUTE_FORCE_SSH", "PORT_SCAN_DETECTED", "SUSPICIOUS_OUTBOUND_BEACON", 
        "DNS_TUNNELING_ATTEMPT", "UNAUTHORIZED_ADMIN_ACCESS"
    );

    private final List<String> severities = List.of("LOW", "MEDIUM", "HIGH", "CRITICAL");
    private final List<String> targetEmails = List.of(
        "employee@cyberquest.internal", "analyst@cyberquest.internal", "workstation-04@internal.lan"
    );

    public ThreatTelemetryService(SecurityLogRepository logRepository) {
        this.logRepository = logRepository;
    }

    @Scheduled(fixedRate = 45000)
    public void ingestSyntheticThreat() {
        if (logRepository.count() >= 25) {
            return; // Prevent unlimited table growth during local runs
        }

        SecurityLog log = new SecurityLog();
        log.setEventType(eventTypes.get(random.nextInt(eventTypes.size())));
        log.setSeverity(severities.get(random.nextInt(severities.size())));
        log.setDescription("Automated telemetry alert generated by network monitor.");
        log.setTargetEmail(targetEmails.get(random.nextInt(targetEmails.size())));
        log.setResolved(false);

        logRepository.save(log);
    }
}